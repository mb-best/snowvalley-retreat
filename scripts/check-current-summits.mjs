import assert from'node:assert/strict';
import{terrainModule}from'./terrain-modules.mjs';
const{loadCurveDraft,prepareCurrentSummitRepair}=await terrainModule('current-summits.js');
const current={trailCurveVersion:1,revision:1001,title:'我的手动草案',features:[{name:'自定义步道'}]};
let fallbackCalls=0,activeCalls=0;
const options={readStored:()=>JSON.stringify(current),readActive:()=>{activeCalls++;return JSON.stringify(current);},readBaseline:()=>{fallbackCalls++;return{...current,title:'发布底稿'};},validate:d=>d};
assert.deepEqual(await loadCurveDraft(options),{document:current,source:'browser'});
assert.equal(fallbackCalls,0);assert.equal(activeCalls,0);
assert.deepEqual(await loadCurveDraft({...options,readStored:()=>JSON.stringify({storage:'indexeddb'})}),{document:current,source:'browser'});
assert.equal(activeCalls,1);assert.equal(fallbackCalls,0);
await assert.rejects(loadCurveDraft({...options,readStored:()=>'{broken'}));
await assert.rejects(loadCurveDraft({...options,readStored:()=>JSON.stringify({storage:'indexeddb'}),readActive:()=>null}));
assert.equal(fallbackCalls,0,'An unreadable original must never be replaced by a fallback');
assert.equal((await loadCurveDraft({...options,readStored:()=>null})).source,'published-curves');
await assert.rejects(loadCurveDraft({...options,readStored:()=>JSON.stringify({trailCurveVersion:0})}));
const saved=structuredClone(current),repair=d=>({document:{...d,summitRepairVersion:1}});let backup;
const result=await prepareCurrentSummitRepair(current,{repair,saveBackup:raw=>{backup=JSON.parse(raw);}});
assert.deepEqual(backup,saved);assert.deepEqual(current,saved);assert.equal(result.document.summitRepairVersion,1);
assert.equal(await prepareCurrentSummitRepair(result.document,{repair:()=>assert.fail('Already repaired'),saveBackup:()=>assert.fail('Already repaired')}),null);
await assert.rejects(prepareCurrentSummitRepair(current,{repair,saveBackup:()=>{throw Error('Backup storage unavailable');}}));
assert.deepEqual(current,saved,'A failed backup must leave the active original untouched');
console.log('Current curve draft: local and IndexedDB originals preserved, explicit fallback, corrupt data refusal, backup before apply, idempotence passed.');
